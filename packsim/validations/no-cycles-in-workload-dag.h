#pragma once

#include <optional>

#include "packsim/validations/validation.h"

namespace packsim::details {

class NoCyclesInWorkloadDag : public Validation {
 public:
  NoCyclesInWorkloadDag()
      : Validation(
            "NoCyclesInWorkloadDag",
            "workload::thrift::WorkloadDag::workloadDependencies should be cycle free.") {
  }

  /**
   * Detect cycles using dfs in directed graph generated by
   * WorkloadDag::workloadDependencies.
   *
   * @param simCfg          The simulation configuration to validate
   * @param ignoreWarnings  Whether to ignore warnings during validation
   * @return                Validation result if a cycle is detected, or
   *                        std::nullopt if no cycles found
   */
  std::optional<ValidationResult> validate(
      thrift::Simulation const& simCfg,
      bool const ignoreWarnings) const final;
};
} // namespace packsim::details
